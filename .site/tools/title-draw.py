#!/usr/bin/env python3
# Writes pages/demos-title.contract: the /demos title's glyph outlines ("Demos", Inter at weight 600 and opsz 32, the
# optical size Chrome picks for it at 144 px) as one SVG, shaped as the browser shapes it (HarfBuzz: kerning, the
# -0.04em tracking after every letter) and placed on the text's own line box (line-height 1, the font's hhea
# ascent/descent, as Chrome's half-leading model): an em-sized drawing that lies exactly over the title, for its
# draw-on entrance (docs/decisions.md D17). Needs fonttools, skia-pathops and uharfbuzz (a throwaway venv):
#   python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools brotli skia-pathops uharfbuzz && /tmp/ft/bin/python -I tools/title-draw.py
import io, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

site = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORD, WGHT, OPSZ, TRACK, LH = 'Demos', 600, 32, -0.04, 1.0
font = instantiateVariableFont(TTFont(os.path.join(site, 'assets/fonts/InterAscii.woff2')), {'wght': WGHT, 'opsz': OPSZ})
font.flavor = None
# The instance keeps the variable font's overlapping contours (a stem over a bowl): merged, so each stroke is an outline.
removeOverlaps(font, ['D', 'e', 'm', 'o', 's'])
buf = io.BytesIO(); font.save(buf); data = buf.getvalue()
upm = font['head'].unitsPerEm
asc, desc = font['hhea'].ascent, -font['hhea'].descent
hbfont = hb.Font(hb.Face(data))
b = hb.Buffer(); b.add_str(WORD); b.guess_segment_properties(); hb.shape(hbfont, b, {'kern': True, 'liga': True})
gs = font.getGlyphSet()
order = font.getGlyphOrder()
track = TRACK * upm
baseline = (LH * upm - (asc + desc)) / 2 + asc  # from the line box's top, in font units
x = 0.0
glyphs = []
for info, pos in zip(b.glyph_infos, b.glyph_positions):
    name = order[info.codepoint]
    pen = SVGPathPen(gs, lambda v: f'{round(v, 1):g}')
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, baseline - pos.y_offset)))
    # one path per contour, so each closed outline draws on its own
    contours = [('M' + c).strip() for c in pen.getCommands().split('M') if c.strip()]
    glyphs.append(contours)
    x += pos.x_advance + track
width = x  # Chrome adds the tracking after the last letter too
w_em = width / upm
lines = [
    '// Generated by tools/title-draw.py: do not edit. The /demos title\'s outlines (Inter 600, opsz 32), one path per contour,',
    '// on the text\'s 1 em line box; the draw-on entrance is web/head.css\'s (data-motion d-draw, by :nth-child).',
    '// Contours per letter: ' + ', '.join(f'{c}: {len(g)}' for c, g in zip(WORD, glyphs)) + '.',
    'component TitleDraw',
    '  props',
    '    top: string',
    '    size: string',
    '  view',
    f'    svg viewBox="0 0 {round(width, 1):g} {upm}" width="{w_em:.4f}em" height="1em" font-size=size position="absolute" left=0 top=0 margin-top=top',
    '      overflow="visible" pointer-events="none" aria-hidden=true data-motion="lift-20 d-title d-draw" fill="none"',
]
for i, contours in enumerate(glyphs):
    for d in contours:
        lines.append(f'      path d="{d}" pathLength=1')
open(os.path.join(site, 'pages/demos-title.contract'), 'w').write('\n'.join(lines) + '\n')
print(f'demos-title.contract: {sum(map(len, glyphs))} contours, {w_em:.4f} em wide, baseline {baseline / upm:.4f} em')
