#!/usr/bin/env bun
// Writes web/preloads.js into every built page's head, with this build's content chunk names (docs/decisions.md
// D24): each page then preloads only its own content (an article, a doc, the cards), and any other on intent.
//   bun tools/preloads.ts [dist]      (part of `bun run build`, after tools/seo/postbuild.ts)
// Fails the build when Exact's entry no longer prepares its chunks the way web/preloads.js holds them back, or when a
// content module (content-gen/index.ts) has no chunk of its own: either would leave the hold silently doing nothing.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const SITE = resolve(import.meta.dir, '..');
// content-gen/ is generated by the build (tools/gen-content.ts): imported at run time, so the tooling typechecks without it.
const { articleSlugs, docSlugs, demoPostSlugs }: { articleSlugs: string[]; docSlugs: string[]; demoPostSlugs: string[] } = await import(join(SITE, 'content-gen/index.ts'));
const dist = resolve(SITE, process.argv[2] ?? 'dist');
const MARK = 'data-reactiive-preloads';
const routes = JSON.parse(readFileSync(join(dist, 'routes.json'), 'utf8'));
const files = Object.values(routes.files as Record<string, string>);
const entry = routes.files['app.js'];
if (!entry) throw new Error('preloads: routes.json names no app.js');
const code = readFileSync(join(dist, entry), 'utf8');
// Exact's entry: `for (const name of [...]) document.head.append(Object.assign(document.createElement('link'), { rel:
// 'modulepreload', ...` (host/web-js/build.mjs), minified.
if (!/document\.head\.append\(Object\.assign\(document\.createElement\([`'"]link[`'"]\),\s*\{\s*rel:\s*[`'"]modulepreload[`'"]/.test(code)) {
  throw new Error(`preloads: ${entry} no longer appends its chunks' modulepreloads to document.head: web/preloads.js would hold nothing back`);
}
// Rolldown names a chunk after its module: <slug>-<8 characters of hash>.js.
const chunkOf = (stem: string) => {
  const found = files.filter((f) => f.length === stem.length + 12 && f.startsWith(`${stem}-`) && f.endsWith('.js'));
  if (found.length !== 1) throw new Error(`preloads: ${found.length} chunks for the content module ${stem} (${found.join(', ') || 'none'})`);
  if (!code.includes(found[0])) throw new Error(`preloads: ${entry} does not prepare ${found[0]}: Exact's preloads changed`);
  return found[0];
};
const chunks = {
  cards: chunkOf('cards'),
  articles: Object.fromEntries(articleSlugs.map((s) => [s, chunkOf(s)])),
  docs: Object.fromEntries(docSlugs.map((s) => [s, chunkOf(s)])),
};
// The demo posts' chunks are held by their name (web/preloads.js): each must have one, and no other chunk the name.
for (const s of demoPostSlugs) chunkOf(`demo-${s}`);
const named = files.filter((f) => /^demo-[a-z0-9-]+-[\w-]{8}\.js$/.test(f));
if (named.length !== demoPostSlugs.length) throw new Error(`preloads: ${named.length} chunks named demo-*, ${demoPostSlugs.length} demo posts: web/preloads.js would hold another's`);
const source = readFileSync(join(SITE, 'web/preloads.js'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').split('\n').map((l) => l.trim())
  .filter((l) => l && !l.startsWith('//')).join('\n');
if (!source.includes("'__REACTIIVE_CHUNKS__'")) throw new Error('preloads: web/preloads.js lost its placeholder');
const tag = `<script ${MARK}>${source.replace("'__REACTIIVE_CHUNKS__'", () => JSON.stringify(chunks))}</script>`;
if (tag.slice(0, -'</script>'.length).includes('</script')) throw new Error('preloads: the script cannot be inlined');

let pages = 0;
const walk = (dir: string) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { if (!name.startsWith('.')) walk(p); continue; }
    if (!name.endsWith('.html')) continue;
    let html = readFileSync(p, 'utf8');
    if (html.includes(MARK)) html = html.replace(new RegExp(`<script ${MARK}>[\\s\\S]*?</script>`), '');
    // Exact writes no <head> tag: the head is what precedes the page's markup, opened by <meta charset>; the script goes
    // right after it, before Exact's own scripts (tools/storage-bridge.ts, run after this, puts its own first).
    const m = /<meta charset=[^>]*>/i.exec(html);
    if (!m) throw new Error(`preloads: no <meta charset> in ${p}`);
    const end = m.index + m[0].length;
    writeFileSync(p, html.slice(0, end) + tag + html.slice(end));
    pages++;
  }
};
walk(dist);
const held = 1 + articleSlugs.length + docSlugs.length + demoPostSlugs.length;
console.log(`preloads: ${held} content chunks held back to their own pages in ${pages} pages' heads (${tag.length} bytes)`);
