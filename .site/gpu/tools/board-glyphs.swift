// Writes textures/board-glyphs.png and src/board_glyphs.rs: the board's coordinate labels
// ("1"…"8", "a"…"h") in the system font at its 8 pt optical size, as an alpha atlas the board
// surface draws (react-native-chessboard draws them as Skia text in the system font, 0.15 of a
// square; the Contract board drew them as `text` in `system-ui`).
//
// Run: swift gpu/tools/board-glyphs.swift
import CoreGraphics
import CoreText
import Foundation
import ImageIO
import UniformTypeIdentifiers

let crate = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let size: CGFloat = 8            // the optical size the labels are drawn at (0.15 of a ~52 pt square)
let scale: CGFloat = 8           // atlas pixels per point: an em of 64 px
let pad: CGFloat = 2             // atlas pixels around each glyph's ink
let font = CTFontCreateUIFontForLanguage(.system, size, nil)!
let ascent = CTFontGetAscent(font), descent = CTFontGetDescent(font)

struct Cell { var ch: String; var ink: CGRect; var x: Int; var w: Int; var h: Int }
var cells: [Cell] = []
var x = 0, height = 0
for ch in "12345678abcdefgh".map(String.init) {
    let line = CTLineCreateWithAttributedString(NSAttributedString(string: ch, attributes: [
        NSAttributedString.Key(kCTFontAttributeName as String): font]))
    let ink = CTLineGetImageBounds(line, nil)
    let w = Int(ceil(ink.width * scale + 2 * pad)), h = Int(ceil(ink.height * scale + 2 * pad))
    cells.append(Cell(ch: ch, ink: ink, x: x, w: w, h: h))
    x += w + 2
    height = max(height, h)
}
let width = x
let ctx = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: width,
                    space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
ctx.setFillColor(gray: 0, alpha: 1)
ctx.fill(CGRect(x: 0, y: 0, width: width, height: height))
ctx.setAllowsFontSmoothing(false)
ctx.setShouldSubpixelPositionFonts(true)
for c in cells {
    let line = CTLineCreateWithAttributedString(NSAttributedString(string: c.ch, attributes: [
        NSAttributedString.Key(kCTFontAttributeName as String): font,
        NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(gray: 1, alpha: 1)]))
    ctx.saveGState()
    // CoreGraphics' origin is bottom-left; the bitmap's first row is its top: every cell starts at row 0.
    ctx.translateBy(x: CGFloat(c.x) + pad - c.ink.minX * scale, y: CGFloat(height - c.h) + pad - c.ink.minY * scale)
    ctx.scaleBy(x: scale, y: scale)
    ctx.textPosition = .zero
    CTLineDraw(line, ctx)
    ctx.restoreGState()
}
let png = crate.appendingPathComponent("textures/board-glyphs.png")
let dest = CGImageDestinationCreateWithURL(png as CFURL, UTType.png.identifier as CFString, 1, nil)!
CGImageDestinationAddImage(dest, ctx.makeImage()!, nil)
CGImageDestinationFinalize(dest)

func f(_ v: CGFloat) -> String { String(format: "%.5f", Double(v)) }
var rs = """
// @generated by tools/board-glyphs.swift from the system font: edit the script, not this.
//! The board's coordinate labels in `textures/board-glyphs.png` (an alpha atlas,
//! \(Int(scale)) px per point of an \(Int(size)) pt font).

/// The atlas's size in pixels.
pub const ATLAS: [u32; 2] = [\(width), \(height)];
/// Atlas pixels per em.
pub const EM_PX: f32 = \(Int(scale * size)).0;
/// The font's ascent and descent, in ems.
pub const ASCENT: f32 = \(f(ascent / size));
pub const DESCENT: f32 = \(f(descent / size));
/// Per glyph ("1"…"8", "a"…"h"): its cell in the atlas (x, y, width, height, pixels) and
/// that cell's box in ems from the pen on the baseline (left, top, width, height; y down).
pub const GLYPHS: [([f32; 4], [f32; 4]); 16] = [

"""
for c in cells {
    let left = (c.ink.minX * scale - pad) / scale / size
    let top = -(c.ink.maxY * scale + pad) / scale / size
    rs += "    ([\(c.x).0, 0.0, \(c.w).0, \(c.h).0], [\(f(left)), \(f(top)), \(f(CGFloat(c.w) / scale / size)), \(f(CGFloat(c.h) / scale / size))]), // \(c.ch)\n"
}
rs += "];\n"
try! rs.write(to: crate.appendingPathComponent("src/board_glyphs.rs"), atomically: true, encoding: .utf8)
print("wrote \(png.path) \(width)x\(height)")
