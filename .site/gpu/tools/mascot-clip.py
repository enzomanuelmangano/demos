#!/usr/bin/env python3
"""Writes src/mascot_clip.rs: the offer mascot's per-frame eye tables and the
morph's haptic beats, read from the RN app's onboarding/ghost-clip.ts.

    python3 gpu/tools/mascot-clip.py [path/to/ghost-clip.ts]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/Desktop/Work/wogi/memocards/apps/patterns/onboarding/ghost-clip.ts')
OUT = os.path.join(HERE, '..', 'src', 'mascot_clip.rs')

ts = open(SRC).read()

def table(name):
    m = re.search(r'export const ' + name + r'\s*=\s*\[(.*?)\];', ts, re.S)
    if not m:
        sys.exit(f'{name} not found in {SRC}')
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?(?:e-?\d+)?', body)]

def const(name):
    return float(re.search(r'export const ' + name + r'\s*=\s*([\d.]+)', ts).group(1))

haptics = re.findall(r"\{\s*at:\s*([\d.]+),\s*kind:\s*'(\w+)'\s*\}", ts[ts.index('MORPH_HAPTICS'):])

lines = ['// @generated by tools/mascot-clip.py from the RN app\'s onboarding/ghost-clip.ts: edit the',
         '// script, not this. The mascot\'s eyes per clip frame (24 fps) and the morph\'s haptics.',
         '']
lines.append(f'pub const EYES_APPEAR_FRAME: f32 = {const("EYES_APPEAR_FRAME")};')
for name in ['EYE_OPEN_T', 'EYE_CY_T', 'EYE_CZ_T', 'EYE_YAW_T', 'EYE_PITCH_T', 'PUP_R_T', 'PUP_U_T']:
    vals = table(name)
    lines.append(f'pub const {name}: [f32; {len(vals)}] = [')
    for i in range(0, len(vals), 10):
        lines.append('    ' + ', '.join(repr(v) if '.' in repr(v) else repr(v) + '.0' for v in vals[i:i + 10]) + ',')
    lines.append('];')
# The gaze's rest (gazeRestAt): the pawn's mean yaw before the longest shut run, the float's
# mean after, ramped across the run.
OPEN, YAW = table('EYE_OPEN_T'), table('EYE_YAW_T')
FLOAT_FROM, FLOAT_TO, BEAT_FROM = 151, 313, 1
best, run = (0, 0), -1
for f in range(0, FLOAT_FROM + 1):
    shut = (OPEN[f] if f < len(OPEN) else 1) == 0
    if shut and run < 0:
        run = f
    if (not shut or f == FLOAT_FROM) and run >= 0:
        if f - run > best[1] - best[0]:
            best = (run, f)
        run = -1
mean = lambda a, b: sum(YAW[min(f, len(YAW) - 1)] for f in range(a, b)) / max(1, b - a)
lines.append('/// gazeRestAt: the shut run the rest ramps across (frames), and the rests either side.')
lines.append(f'pub const SHUT_RUN: (f32, f32) = ({float(best[0])}, {float(best[1])});')
lines.append(f'pub const BEAT_REST: f32 = {mean(BEAT_FROM, best[0])!r};')
lines.append(f'pub const FLOAT_REST: f32 = {mean(FLOAT_FROM, FLOAT_TO)!r};')
lines.append(f'/// (clip seconds, kind) — MORPH_HAPTICS.')
lines.append(f'pub const MORPH_HAPTICS: [(f32, &str); {len(haptics)}] = [')
for at, kind in haptics:
    lines.append(f'    ({float(at)}, "{kind}"),')
lines.append('];')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', os.path.relpath(OUT))
