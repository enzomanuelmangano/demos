// Generates demos.contract (the launcher's list) and assets/app-icons/ from the
// React Native app's registry, so both apps list the same demos in the same order.
//
//   bun tools/gen-demos.ts
//
// RN sources (read-only): src/animations/registry.ts (AnimationRegistry order,
// AnimationMetadata), src/animations/inspirations.ts, assets/app-icons/*.png and
// src/navigation/home/icon-colors.generated.ts. The order mirrors
// src/navigation/home/demos.ts: registry order, reversed (newest first).
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { getInspirationCopy } from '../../../src/navigation/home/inspiration-copy';

const APP = resolve(import.meta.dir, '..');
const RN = resolve(APP, '../..');
const src = (p: string) => readFileSync(resolve(RN, p), 'utf8');

// An object literal of plain values, taken from the text between `start` and `end`.
const literal = (text: string, start: string, end: string): Record<string, Record<string, unknown>> => {
  const from = text.indexOf(start);
  const to = text.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`no ${start}`);
  return new Function(`return ${text.slice(from + start.length - 1, text.indexOf("}", to) + 1)}`)();
};

const registry = src('src/animations/registry.ts');
const order = [...registry.slice(registry.indexOf('export const AnimationRegistry = {'), registry.indexOf('} as const', registry.indexOf('export const AnimationRegistry = {')))
  .matchAll(/^\s+'?([a-z0-9-]+)'?:\s/gm)].map(m => m[1]);
const meta = literal(registry, 'export const AnimationMetadata: Record<string, AnimationMetadataType> = {', '} as const;');
const inspirations = literal(src('src/animations/inspirations.ts'), 'export const AnimationInspirations: Record<string, InspirationData> = {', '} as const;');
const colors = literal(src('src/navigation/home/icon-colors.generated.ts'), 'export const ICON_COLORS: Record<string, string> = {', '\n};') as unknown as Record<string, string>;

// Demos ported to Exact: those demos/index.contract registers (`if slug == "<slug>"`).
const portedIndex = resolve(APP, 'demos/index.contract');
const ported = new Set(existsSync(portedIndex)
  ? [...readFileSync(portedIndex, 'utf8').matchAll(/if slug == "([a-z0-9-]+)"/g)].map(m => m[1])
  : []);

mkdirSync(resolve(APP, 'assets/app-icons'), { recursive: true });
const iconOf = (slug: string) => {
  const own = resolve(RN, `assets/app-icons/${slug}.png`);
  const file = existsSync(own) ? `${slug}.png` : '_placeholder.png';
  copyFileSync(resolve(RN, `assets/app-icons/${file}`), resolve(APP, `assets/app-icons/${file}`));
  return `assets/app-icons/${file}`;
};

const q = (s: string) => JSON.stringify(s);
const rows = order
  .filter(slug => meta[slug] !== undefined)
  .reverse()
  .map(slug => {
    const m = meta[slug] as { name: string; displayName?: string; alert?: boolean };
    const link = (inspirations[slug]?.link as string | null) ?? '';
    // The Inspiration sheet's copy, from the RN app's own wording (inspiration-copy.ts).
    const copy = getInspirationCopy(slug);
    return `    Demo(slug=${q(slug)}, name=${q(m.name)}, label=${q(m.displayName ?? m.name)}, icon=${q(iconOf(slug))}, backdrop=${q(colors[slug] ?? '#ffffff')}, inspiration=${q(link)}, story=${q(copy?.story ?? '')}, actionLabel=${q(copy?.action.label ?? '')}, actionUrl=${q(copy?.action.url ?? '')}, unstable=${m.alert === true}, ported=${ported.has(slug)})`;
  });

writeFileSync(resolve(APP, 'demos.contract'), `// GENERATED by tools/gen-demos.ts from the RN registry: do not edit by hand.
// The launcher's demos, newest first (src/navigation/home/demos.ts).

shape Demo
  slug: string
  name: string
  label: string
  icon: string
  backdrop: string
  inspiration: string
  story: string
  actionLabel: string
  actionUrl: string
  unstable: bool
  ported: bool

fn allDemos(): Demo[] =
  [
${rows.join(',\n')}
  ]
`);
console.log(`${rows.length} demos, ${ported.size} ported`);
