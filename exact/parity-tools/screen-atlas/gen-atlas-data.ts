// Writes exact/demos/home/atlas-data.contract: the parity queue's status per demo and the last
// RN-vs-Exact iOS score (out/scores.json), for the app's own `atlas` route.
//   bun gen-atlas-data.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEMOS, OUT, demos } from "./lib";

const list = demos();
const by = (s: string) => JSON.stringify(list.filter((d) => d.status === s).map((d) => d.slug));
const scores: Record<string, { mean: number }> = existsSync(join(OUT, "scores.json")) ? JSON.parse(readFileSync(join(OUT, "scores.json"), "utf8")) : {};
const scored = Object.keys(scores);
const file = join(DEMOS, "home/atlas-data.contract");
writeFileSync(file, `// GENERATED by exact/parity-tools/screen-atlas/gen-atlas-data.ts from tools/parity-queue.txt and
// the atlas's last iOS scores: do not edit by hand.

fn atlasDone(): string[] = ${by("done")}
fn atlasOpen(): string[] = ${by("open")}
fn atlasClaimed(): string[] = ${by("claimed")}
fn atlasStatus(slug: string): string = atlasDone().includes(slug) ? "done" : atlasOpen().includes(slug) ? "open" : atlasClaimed().includes(slug) ? "claimed" : "unverified"

fn atlasScored(): string[] = ${JSON.stringify(scored)}
fn atlasScores(): number[] = ${JSON.stringify(scored.map((k) => scores[k].mean))}
// Mean per-pixel difference (0-255) between the RN and Exact iOS captures; -1 when not captured.
fn atlasScore(slug: string): number = match atlasScores().at(atlasScored().indexOf(slug)) {
  case some(v) => atlasScored().includes(slug) ? v : -1,
  case none => -1
}
`);
console.log(file);
