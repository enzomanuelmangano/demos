// github-terrain: writes what gpu/src/github_terrain.rs draws, from the RN demo's own code.
// - exact/demos/gpu/shaders/github_terrain.wgsl: the RN vertex and fragment strings
//   (src/animations/github-terrain/shaders) with their `${CONSTANT}`s interpolated by the app's
//   own JS, each `fn main` renamed after its stage. Nothing else of the text changes.
// - exact/demos/gpu/images/github-terrain/scene.bin: buildSceneData(getContributionGrid(false))
//   (set A, synthetic) and (true) (set B, real), as the renderer uploads them: colors u32,
//   positions f32×4, heights f32, heightGridFlat f32 (A), then colors, heights, heightGridFlat (B).
//   Bit for bit what RN's Float32Array / Uint32Array hold.
//   bun exact/parity-tools/github-terrain/build.ts
import { vertexShader, fragmentShader } from '../../../src/animations/github-terrain/shaders';
import { getContributionGrid } from '../../../src/animations/github-terrain/contribution-data';
import { buildSceneData } from '../../../src/animations/github-terrain/utils/scene-data';

const demos = new URL('../../demos/', import.meta.url).pathname;
const one = (src: string, entry: string) => {
  if (src.split('fn main(').length !== 2) throw new Error(`${entry}: one fn main expected`);
  return src.replace('fn main(', `fn ${entry}(`).trim();
};
const wgsl = `// GENERATED by exact/parity-tools/github-terrain/build.ts from the RN demo's shaders
// (src/animations/github-terrain/shaders/{vertex,fragment}.ts) with their constants interpolated
// as the app does: do not edit by hand. Each \`fn main\` is named after its stage.

// ---- vertex.ts ----

${one(vertexShader, 'vs_main')}

// ---- fragment.ts ----

${one(fragmentShader, 'fs_main')}
`;
await Bun.write(`${demos}gpu/shaders/github_terrain.wgsl`, wgsl);

const a = buildSceneData(getContributionGrid(false));
const b = buildSceneData(getContributionGrid(true));
const parts = [
  new Uint32Array(a.colors), new Float32Array(a.positions), new Float32Array(a.heights), a.heightGridFlat,
  new Uint32Array(b.colors), new Float32Array(b.heights), b.heightGridFlat,
];
const bytes = new Uint8Array(parts.reduce((n, p) => n + p.byteLength, 0));
let o = 0;
for (const p of parts) { bytes.set(new Uint8Array(p.buffer, p.byteOffset, p.byteLength), o); o += p.byteLength; }
await Bun.write(`${demos}gpu/images/github-terrain/scene.bin`, bytes);
console.log(a.colors.length, b.colors.length, a.heightGridFlat.length, bytes.byteLength);
