// Writes exact/demos/gpu/shaders/cherry_blossom_qrcode.wgsl from the RN demo's own shader strings
// (src/animations/cherry-blossom-qrcode/shaders), every `${CONSTANT}` interpolated by the same JS
// that interpolates them in the app. The eight modules (sky, shadow, blocks and dust, a vertex and
// a fragment each) become one: the shared Uniforms struct, shaderUtils, the five bindings and
// `const BLOCK` once at the top, each `fn main` named after its pass and stage. Nothing else of
// the text changes.
//   bun exact/parity-tools/cherry-blossom-qrcode/wgsl.ts
import * as S from '../../../src/animations/cherry-blossom-qrcode/shaders';
import { shaderUtils, uniformsStruct } from '../../../src/animations/cherry-blossom-qrcode/shaders/helpers';
import { BLOCK_SIZE } from '../../../src/animations/cherry-blossom-qrcode/constants';

const out = new URL('../../demos/gpu/shaders/cherry_blossom_qrcode.wgsl', import.meta.url).pathname;

const BINDINGS = [
  '@group(0) @binding(0) var<uniform> uniforms: Uniforms;',
  '@group(0) @binding(1) var<storage, read> blockTypes: array<u32>;',
  '@group(0) @binding(2) var<storage, read> blockPositions: array<vec4f>;',
  '@group(0) @binding(3) var<storage, read> blockResistance: array<f32>;',
  '@group(0) @binding(4) var<storage, read> blockBaseY: array<f32>;',
];
const BLOCK = `const BLOCK = ${BLOCK_SIZE};`;

const body = (src: string, entry: string) => {
  let s = src.split(uniformsStruct).join('').split(shaderUtils).join('');
  s = s
    .split('\n')
    .filter((line) => !BINDINGS.includes(line.trim()) && line.trim() !== BLOCK)
    .join('\n');
  if (s.split('fn main(').length !== 2) throw new Error(`${entry}: one fn main expected`);
  return s.replace('fn main(', `fn ${entry}(`).replace(/\n{3,}/g, '\n\n').trim();
};

const passes: [string, string, string][] = [
  ['skyVertexShader', 'sky_vs', 'sky.ts skyVertexShader'],
  ['skyFragmentShader', 'sky_fs', 'sky.ts skyFragmentShader'],
  ['shadowVertexShader', 'shadow_vs', 'shadow.ts shadowVertexShader'],
  ['shadowFragmentShader', 'shadow_fs', 'shadow.ts shadowFragmentShader'],
  ['blocksVertexShader', 'blocks_vs', 'blocks-vertex.ts blocksVertexShader'],
  ['blocksFragmentShader', 'blocks_fs', 'blocks-fragment.ts blocksFragmentShader'],
  ['dustVertexShader', 'dust_vs', 'dust.ts dustVertexShader'],
  ['dustFragmentShader', 'dust_fs', 'dust.ts dustFragmentShader'],
];

let text = `// GENERATED by exact/parity-tools/cherry-blossom-qrcode/wgsl.ts from the RN demo's shaders
// (src/animations/cherry-blossom-qrcode/shaders/*.ts) with their constants interpolated as the app
// does: do not edit by hand. One module for the eight RN modules; each \`fn main\` is named after
// its pass. gpu/src/cherry_blossom_qrcode.rs draws sky, shadow, blocks and dust in that order.
${uniformsStruct.trim()}

${shaderUtils.trim()}

${BINDINGS.join('\n')}

${BLOCK}
`;
for (const [name, entry, from] of passes) {
  text += `\n// ---- ${from} ----\n\n${body((S as Record<string, string>)[name], entry)}\n`;
}
await Bun.write(out, text);
console.log(out);
